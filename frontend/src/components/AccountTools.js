import React, { useState } from "react";
import API from "../services/api";

/* Account creation tools (single account + CSV import). Account management belongs to the IT Admin,
   so these live here and are used by the IT Admin dashboard only. */

export const STAFF_ROLE_OPTIONS = [
  { label: "Registrar", role: "registrar", faculty_type: null, idPrefix: "R" },
  { label: "Dean", role: "faculty", faculty_type: "dean", idPrefix: "D" },
  { label: "Full-time Faculty", role: "faculty", faculty_type: "full_time", idPrefix: "F" },
  { label: "Part-time Faculty", role: "faculty", faculty_type: "part_time", idPrefix: "P" },
];

/* One-at-a-time account creation -- the bulk CSV importer below still exists
   for a big list, but adding staff one by one (e.g. while waiting on a full
   roster) shouldn't require writing a CSV row for a single person.
   Default password is the school ID (not a fixed "welcome123"), matching
   this system's existing convention everywhere else (reset-password flow,
   bulk-create) -- every new account is forced to change it on first login,
   the same as the bulk path. */
export function AddStaffModal({ onClose, onCreated }) {
  const [form, setForm] = useState({ firstName: "", lastName: "", schoolId: "", roleIndex: "2", department: "", specializations: "" });
  const [submitting, setSubmitting] = useState(false);
  const [result, setResult] = useState(null);

  const selected = STAFF_ROLE_OPTIONS[Number(form.roleIndex)];
  const isFaculty = selected.role === "faculty";
  const autoId = selected.role === "registrar" || selected.faculty_type === "dean";   // generated by the system

  const submit = async () => {
    if (!form.firstName.trim() || !form.lastName.trim() || (!autoId && !form.schoolId.trim())) return;
    setSubmitting(true);
    setResult(null);
    try {
      const row = {
        school_id: autoId ? "" : form.schoolId.trim(),
        first_name: form.firstName.trim(),
        last_name: form.lastName.trim(),
        role: selected.role,
        faculty_type: selected.faculty_type || undefined,
        department: form.department.trim(),
        specializations: isFaculty
          ? form.specializations.split(",").map((s) => s.trim()).filter(Boolean)
          : [],
      };
      const res = await API.post("/accounts/bulk-create/", { users: [row] });
      if (res.data.created.length > 0) {
        setResult({ ok: true, text: `Account created: ${res.data.created[0]} (School ID ${String(res.data.created[0]).replace(/^UPHM-/, "")}; default password = School ID; must be changed on first login).` });
        onCreated?.();
        setForm({ firstName: "", lastName: "", schoolId: "", roleIndex: "2", department: "", specializations: "" });
      } else {
        const err = res.data.errors[0]?.errors;
        setResult({ ok: false, text: err ? JSON.stringify(err) : "Could not create the account." });
      }
    } catch (err) {
      setResult({ ok: false, text: err.response?.data?.detail || "Request failed." });
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <div style={{
      position: "fixed", inset: 0, background: "rgba(15,23,42,0.45)",
      display: "flex", alignItems: "center", justifyContent: "center", zIndex: 1000,
    }}>
      <div style={{ background: "white", borderRadius: "12px", padding: "28px", width: "440px", maxWidth: "90vw" }}>
        <div style={{ display: "flex", justifyContent: "space-between", alignItems: "flex-start" }}>
          <div>
            <h3 style={{ margin: 0, color: "#003366" }}>Add Staff Account</h3>
            <p style={{ margin: "4px 0 0", fontSize: "12.5px", color: "#64748b" }}>
              A default password (the School ID) is set; they'll be asked to change it on first login.
            </p>
          </div>
          <button onClick={onClose} style={{ border: "none", background: "none", fontSize: "18px", cursor: "pointer", color: "#64748b" }}>Close</button>
        </div>

        <div style={{ display: "grid", gridTemplateColumns: "1fr 1fr", gap: "12px", marginTop: "18px" }}>
          <div>
            <label style={{ fontSize: "12.5px", fontWeight: 600, color: "#333" }}>First Name</label>
            <input value={form.firstName} onChange={(e) => setForm({ ...form, firstName: e.target.value })}
                   style={{ width: "100%", padding: "9px", borderRadius: "6px", border: "1px solid #cdd6e0", marginTop: "4px", boxSizing: "border-box" }} />
          </div>
          <div>
            <label style={{ fontSize: "12.5px", fontWeight: 600, color: "#333" }}>Last Name</label>
            <input value={form.lastName} onChange={(e) => setForm({ ...form, lastName: e.target.value })}
                   style={{ width: "100%", padding: "9px", borderRadius: "6px", border: "1px solid #cdd6e0", marginTop: "4px", boxSizing: "border-box" }} />
          </div>
        </div>

        <div style={{ marginTop: "12px" }}>
          <label style={{ fontSize: "12.5px", fontWeight: 600, color: "#333" }}>School ID</label>
          <input placeholder={autoId ? `Generated automatically (next free ${selected.idPrefix}####)` : `e.g. ${selected.idPrefix}1003`}
                 value={autoId ? "" : form.schoolId} disabled={autoId} onChange={(e) => setForm({ ...form, schoolId: e.target.value })}
                 style={{ width: "100%", padding: "9px", borderRadius: "6px", border: "1px solid #cdd6e0", marginTop: "4px", boxSizing: "border-box" }} />
        </div>

        <div style={{ marginTop: "12px" }}>
          <label style={{ fontSize: "12.5px", fontWeight: 600, color: "#333" }}>Role</label>
          <select value={form.roleIndex} onChange={(e) => setForm({ ...form, roleIndex: e.target.value })}
                  style={{ width: "100%", padding: "9px", borderRadius: "6px", border: "1px solid #cdd6e0", marginTop: "4px", boxSizing: "border-box" }}>
            {STAFF_ROLE_OPTIONS.map((opt, i) => <option key={opt.label} value={i}>{opt.label}</option>)}
          </select>
        </div>

        <div style={{ marginTop: "12px" }}>
          <label style={{ fontSize: "12.5px", fontWeight: 600, color: "#333" }}>Department</label>
          <input placeholder="College or department" value={form.department} onChange={(e) => setForm({ ...form, department: e.target.value })}
                 style={{ width: "100%", padding: "9px", borderRadius: "6px", border: "1px solid #cdd6e0", marginTop: "4px", boxSizing: "border-box" }} />
        </div>

        {isFaculty && (
          <div style={{ marginTop: "12px" }}>
            <label style={{ fontSize: "12.5px", fontWeight: 600, color: "#333" }}>Specialization / Degree(s)</label>
            <input placeholder="e.g. BA in Filipino, FCL (comma-separated if more than one)"
                   value={form.specializations} onChange={(e) => setForm({ ...form, specializations: e.target.value })}
                   style={{ width: "100%", padding: "9px", borderRadius: "6px", border: "1px solid #cdd6e0", marginTop: "4px", boxSizing: "border-box" }} />
          </div>
        )}

        {result && (
          <p style={{ marginTop: "12px", fontSize: "13px", color: result.ok ? "#1e7a45" : "#a4231a" }}>{result.text}</p>
        )}

        <div style={{ display: "flex", justifyContent: "flex-end", gap: "10px", marginTop: "20px" }}>
          <button onClick={onClose} style={{
            background: "white", color: "#1f2937", border: "1px solid #cdd6e0", padding: "9px 18px", borderRadius: "6px", cursor: "pointer",
          }}>Cancel</button>
          <button
            onClick={submit}
            disabled={submitting || !form.firstName.trim() || !form.lastName.trim() || !form.schoolId.trim()}
            style={{
              background: "#003366", color: "white", border: "none", padding: "9px 20px",
              borderRadius: "6px", fontWeight: 600, cursor: "pointer",
            }}
          >
            {submitting ? "Creating…" : "Create account"}
          </button>
        </div>
      </div>
    </div>
  );
}

export function BulkCreateAccounts({ onCreated }) {
  const [csvText, setCsvText] = useState("");
  const [feedback, setFeedback] = useState(null);
  const [submitting, setSubmitting] = useState(false);
  const [fileName, setFileName] = useState("");

  const EXAMPLE = "school_id,first_name,last_name,role,faculty_type,department\n"
    + "23-1001,Juan,Dela Cruz,student,,\n"
    + "23-1002,Maria,Santos,faculty,full_time,Computer Studies";

  const parseRows = (text) => {
    const lines = text.trim().split("\n").filter((l) => l.trim().length > 0);
    const [header, ...rows] = lines;
    const cols = header.split(",").map((c) => c.trim());
    return rows.map((row) => {
      const values = row.split(",").map((v) => v.trim());
      return Object.fromEntries(cols.map((c, i) => [c, values[i] || undefined]));
    });
  };

  const submitBulk = async () => {
    if (!csvText.trim()) return;
    setSubmitting(true);
    setFeedback(null);
    try {
      const users = parseRows(csvText);
      const res = await API.post("/accounts/bulk-create/", { users });
      setFeedback(res.data);
      if (res.data.created?.length) onCreated?.();
    } catch (err) {
      setFeedback({ created: [], errors: [{ row: {}, errors: err.response?.data || "Request failed." }] });
    } finally {
      setSubmitting(false);
    }
  };

  const handleFileUpload = (e) => {
    const file = e.target.files[0];
    if (!file) return;
    setFileName(file.name);
    const reader = new FileReader();
    reader.onload = (ev) => setCsvText(ev.target.result);
    reader.readAsText(file);
  };

  const cardStyle = {
    background: "white",
    borderRadius: "10px",
    padding: "24px",
    maxWidth: "720px",
    boxShadow: "0 1px 4px rgba(0,0,0,0.08)",
    border: "1px solid #e0e6ed",
  };

  return (
    <div>
      <h3 style={{ color: "#003366" }}>Bulk-Create User Accounts</h3>

      <div style={cardStyle}>
        <p style={{ fontSize: "13px", color: "#444", marginTop: 0 }}>
          Paste one row per account below, or upload a CSV file. Each row needs:
        </p>
        <code style={{
          display: "inline-block", background: "#f0f4f8", color: "#003366",
          padding: "6px 10px", borderRadius: "6px", fontSize: "12.5px", marginBottom: "14px",
        }}>
          school_id, first_name, last_name, role, faculty_type, department
        </code>

        <textarea
          rows={10}
          placeholder={EXAMPLE}
          value={csvText}
          onChange={(e) => setCsvText(e.target.value)}
          style={{
            width: "100%",
            padding: "14px",
            borderRadius: "8px",
            border: "1px solid #cdd6e0",
            fontFamily: "monospace",
            fontSize: "13px",
            lineHeight: "1.6",
            resize: "vertical",
            boxSizing: "border-box",
            outline: "none",
          }}
          onFocus={(e) => (e.target.style.border = "1px solid #003366")}
          onBlur={(e) => (e.target.style.border = "1px solid #cdd6e0")}
        />

        <div style={{
          display: "flex", justifyContent: "space-between", alignItems: "center",
          marginTop: "8px", fontSize: "12px", color: "#777",
        }}>
          <span>Format: school_id, first_name, last_name, role, faculty_type, department</span>
        </div>

        <div style={{
          marginTop: "16px", padding: "12px 14px", background: "#f0f4f8",
          borderRadius: "8px", fontSize: "12.5px", color: "#333", lineHeight: "1.6",
        }}>
          <div>• Username is generated automatically as <strong>UPHM-&lt;school_id&gt;</strong>.</div>
          <div>• Default password is the <strong>school ID</strong> itself.</div>
          <div>• Every new account is <strong>required to change its password</strong> on first login.</div>
        </div>

        <div style={{
          display: "flex", alignItems: "center", gap: "12px",
          marginTop: "20px", paddingTop: "16px", borderTop: "1px solid #eef1f5",
        }}>
          <button
            onClick={submitBulk}
            disabled={submitting || !csvText.trim()}
            style={{
              background: submitting ? "#6b8bb3" : "#003366",
              color: "white", border: "none", padding: "10px 22px",
              borderRadius: "8px", fontSize: "14px", fontWeight: 600,
              cursor: submitting ? "default" : "pointer", transition: "background 0.15s",
            }}
            onMouseEnter={(e) => { if (!submitting) e.target.style.background = "#0055aa"; }}
            onMouseLeave={(e) => { if (!submitting) e.target.style.background = "#003366"; }}
          >
            {submitting ? "Creating…" : "Create Accounts"}
          </button>

          <label style={{
            display: "inline-flex", alignItems: "center", gap: "6px",
            padding: "10px 18px", borderRadius: "8px", border: "1px dashed #9fb3c8",
            fontSize: "13px", color: "#003366", cursor: "pointer", background: "#f8fafc",
          }}>
            {fileName || "Upload CSV instead"}
            <input type="file" accept=".csv,text/csv" onChange={handleFileUpload} style={{ display: "none" }} />
          </label>
        </div>
      </div>

      {feedback && (
        <div style={{ marginTop: "16px", maxWidth: "720px" }}>
          {feedback.created.length > 0 && (
            <div style={{
              background: "#eafaf0", border: "1px solid #b7e4c7", color: "#1e7a45",
              borderRadius: "8px", padding: "12px 16px", marginBottom: "8px", fontSize: "13px",
            }}>
              ✓ Created {feedback.created.length} account{feedback.created.length > 1 ? "s" : ""}: {feedback.created.join(", ")}
            </div>
          )}
          {feedback.errors.length > 0 && (
            <div style={{
              background: "#fdecea", border: "1px solid #f3b3ac", color: "#a4231a",
              borderRadius: "8px", padding: "12px 16px", fontSize: "13px",
            }}>
              ⚠ {feedback.errors.length} row{feedback.errors.length > 1 ? "s" : ""} failed — check the format and try again.
            </div>
          )}
        </div>
      )}
    </div>
  );
}
